/**
 * Sample playback arithmetic.
 *
 * A sampler plays one recording at many pitches by varying the playback rate: a
 * note twice the root frequency plays at rate 2, an octave down at rate 0.5.
 * That relationship, and the crossfade that makes a recording loop without a
 * seam, are both plain arithmetic over sample data, so they live here — pure,
 * and testable without a browser.
 */

/**
 * The pitch, in Hz, that a bundled sample is recorded at, and the assumption
 * made about a sample you load yourself.
 *
 * A2 is 110 Hz. Matching the instrument's own A tonic means a sample and an
 * oscillator playing the same chord land on the same pitches.
 */
export const DEFAULT_SAMPLE_ROOT_HZ = 110;

/**
 * Playback rate that retunes a recording made at `rootFrequency` to `frequency`.
 *
 * A non-positive root would divide by zero, so it falls back to unity playback
 * rather than producing an `Infinity` rate.
 */
export function playbackRateFor(frequency: number, rootFrequency: number): number {
  if (rootFrequency <= 0) return 1;
  return frequency / rootFrequency;
}

/**
 * Crossfades the start of a recording into its tail so it can loop cleanly, and
 * returns the loop length in samples.
 *
 * The trick is that the loop point stops *before* the buffer ends. A short
 * window at the end of the loop body is the "what would have come next" tail;
 * blending that tail over the first samples of the buffer makes the jump from
 * `loopEnd - 1` back to `0` continuous, because sample 0 now *is* the sample
 * that followed the loop end.
 *
 * Mutates `samples` in place and is a no-op for a buffer too short to hold a
 * fade on both sides.
 */
export function crossfadeForLoop(
  samples: Float32Array,
  sampleRate: number,
  fadeMilliseconds: number,
): number {
  const length = samples.length;
  const fade = Math.min(Math.round((fadeMilliseconds / 1000) * sampleRate), Math.floor(length / 2));

  if (fade <= 0) return length;

  const loopLength = length - fade;

  for (let i = 0; i < fade; i += 1) {
    const alpha = i / fade;
    samples[i] = samples[loopLength + i] * (1 - alpha) + samples[i] * alpha;
  }

  return loopLength;
}

/** A recording shipped with the instrument. */
export interface BundledSample {
  readonly id: string;
  readonly label: string;
  /** Path under the app's base URL, resolved at registration time. */
  readonly file: string;
  /** Pitch the recording is at, in Hz. */
  readonly rootFrequency: number;
}

